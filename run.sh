#!/bin/bash
# Builds the repro with and without padding and prints how long cancelling
# 500 coroutines took, in milliseconds.
set -euo pipefail
cd "$(dirname "$0")"

PADDING=100000

# build SCRATCH. Prints the binary path.
build() {
    swift build --package-path cli -c release --scratch-path "$1" >&2 || exit 1
    echo "$1/release/ReproCLI"
}

# padding COUNT. Writes COUNT empty C functions to make the binary's symbol table bigger.
padding() {
    awk -v n="$1" 'BEGIN {
        print "// Generated by run.sh"
        for (i = 0; i < n; i++) printf "__attribute__((used, noinline)) int padding_%d(void) { return %d; }\n", i, i
    }' > cli/Sources/Padding/Padding.c
}

symbols() {
    nm "$1" | wc -l | tr -d ' '
}

row() {
    printf "%-28s %9s   %-30s %10s %16s\n" "$@"
}

run() {
    local label=$1 bin=$2
    local none default
    read -ra none <<< "$("$bin")"
    read -ra default <<< "$("$bin" --kscrash)"
    row "$label" "$(symbols "$bin")" "cancel 500 collectors" "${none[0]}" "${default[0]}"
    row "" "" "cancel 500 combine collectors" "${none[1]}" "${default[1]}"
}

echo "Building the Kotlin framework (the first run downloads Gradle and Kotlin/Native)..."
./gradlew -q assembleReproKotlinReleaseXCFramework

echo "Building the command line tool..."
padding 0
plain=$(build cli/.build/plain)
padding "$PADDING"
padded=$(build cli/.build/padded)

echo
row "Binary" "Symbols" "Case" "No KSCrash" "KSCrash 2.6.1"
row "------" "-------" "----" "----------" "-------------"
run "No padding" "$plain"
run "$PADDING padding functions" "$padded"
echo
echo "Times are in milliseconds."
